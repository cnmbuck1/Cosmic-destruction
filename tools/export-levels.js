#!/usr/bin/env node
// Exports the level data from web-preview/index.html (the authoring source) to
// CosmicDestruction/Core/Levels.swift, so the web preview and the iOS app always
// play the same levels. Usage: node tools/export-levels.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'web-preview/index.html'), 'utf8');
const start = html.indexOf('const LEVELS = ');
const end = html.indexOf('const starsFor', start);
if (start < 0 || end < 0) throw new Error('LEVELS block not found');
const LEVELS = new Function(html.slice(start, end) + '; return LEVELS;')();

const num = (v) => {
  const r = Math.round(v * 10000) / 10000;
  const t = String(r === 0 ? 0 : r);
  return t.includes('.') || t.includes('e') ? t : t + '';
};
const vec = (a) => `[${a.map(num).join(', ')}]`;
const lines = [];
lines.push('import Foundation');
lines.push('');
lines.push('// GENERATED by tools/export-levels.js from web-preview/index.html.');
lines.push('// Do not edit by hand: change the levels in the web preview and re-run the script.');
lines.push('');
lines.push('/// The hand-designed levels (build 4: 13 levels). Positions are fully');
lines.push('/// deterministic; there is no procedural generation. Pieces are placed with a');
lines.push('/// 4 mm gap so rigid bodies never start interpenetrating.');
lines.push('enum Levels {');
lines.push(`    static let all: [LevelDefinition] = [${LEVELS.map((l) => `level${l.id}`).join(', ')}]`);
lines.push('');
lines.push('    private static func b(_ kind: BlockKind, _ center: SIMD3<Float>, _ size: SIMD3<Float>,');
lines.push('                          target: Bool = true, yaw: Float = 0, neon: NeonColor? = nil) -> BlockSpec {');
lines.push('        BlockSpec(center: center, size: size, kind: kind, isTarget: target, yaw: yaw, neon: neon)');
lines.push('    }');
for (const l of LEVELS) {
  const targets = l.blocks.filter((x) => x.t).length;
  lines.push('');
  lines.push(`    // MARK: Level ${l.id} — ${l.name}`);
  lines.push('');
  lines.push(`    /// ${l.tag} ${l.blocks.length} pieces (${targets} targets), ${l.shots} shots, ${Math.round(l.threshold * 100)}% to win.`);
  // Blocks get their own explicitly typed constant: it keeps type-checking of the big literal fast.
  lines.push(`    private static let blocks${l.id}: [BlockSpec] = [`);
  for (const x of l.blocks) {
    const extra = [];
    if (!x.t) extra.push('target: false');
    if (x.yaw) extra.push(`yaw: ${num(x.yaw)}`);
    if (x.n) extra.push(`neon: .${x.n}`);
    lines.push(`        b(.${x.k}, ${vec(x.c)}, ${vec(x.s)}${extra.length ? ', ' + extra.join(', ') : ''}),`);
  }
  lines.push('    ]');
  lines.push('');
  lines.push(`    static let level${l.id} = LevelDefinition(`);
  lines.push(`        id: ${l.id},`);
  lines.push(`        name: ${JSON.stringify(l.name)},`);
  lines.push(`        tagline: ${JSON.stringify(l.tag)},`);
  lines.push(`        difficulty: ${JSON.stringify(l.diff)},`);
  lines.push(`        gravity: ${num(l.gravity)},`);
  lines.push(`        maxShots: ${l.shots},`);
  lines.push(`        victoryThreshold: ${num(l.threshold)},`);
  lines.push(`        starShotThresholds: [${l.stars.join(', ')}],`);
  lines.push(`        structureOrigin: ${vec(l.origin)},`);
  lines.push(`        blocks: blocks${l.id},`);
  lines.push(`        cameraPullBack: ${num(l.pull || 0)},`);
  lines.push(`        defaultElevation: ${num(l.el)}`);
  lines.push('    )');
}
lines.push('}');
lines.push('');
fs.writeFileSync(path.join(root, 'CosmicDestruction/Core/Levels.swift'), lines.join('\n'));
console.log(`Wrote ${LEVELS.length} levels to CosmicDestruction/Core/Levels.swift`);
